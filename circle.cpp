#include <iostream>
using namespace std;

void circle() {
    float r, a;
    
    cout << "Введите радиус окружности: ";
    cin >> r;
    while (r <= 0) {
        cout << "Введите корректный радиус окружности (положительное число): ";
        cin >> r;
    }
    
    cout << "Введите угол сектора в градусах: ";
    cin >> a;
    while (a < 0 || a > 360) {
        cout << "Введите корректный угол сектора (от 0 до 360 градусов): ";
        cin >> a;
    }
    
    float l = 3.14159265359 * 2 * r;    // Длина окружности 
    float s = 3.14159265359 * r * r;    // Площадь круга
    float s_sector = (a / 360.0) * 3.14159265359 * r * r;    // Площадь сектора 

    cout << "\nРезультаты вычислений:" << endl;
    cout << "Длина окружности: " << l << endl;
    cout << "Площадь круга: " << s << endl;
    cout << "Площадь сектора: " << s_sector << endl;
}

int main() {
    circle();
    return 0;
}